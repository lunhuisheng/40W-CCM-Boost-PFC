% Create a load-dynamic work model without modifying the verified baseline.

clear;
bdclose('all');
designDir=fileparts(mfilename('fullpath'));
sourceFile=fullfile(designDir,'BoostPFC_Design_ControlledStartup.slx');
modelName='BoostPFC_Design_LoadConnection';
modelFile=fullfile(designDir,[modelName '.slx']);
assert(isfile(sourceFile),'Missing verified source model: %s',sourceFile);
assert(~isfile(modelFile),['Work model already exists. Refusing to overwrite it: ' ...
    '%s'],modelFile);
copyfile(sourceFile,modelFile);
load_system(modelFile);

set_param(modelName,'InitFcn',[ ...
    'modelFile=get_param(bdroot,''FileName''); ', ...
    'run(fullfile(fileparts(modelFile),''BoostPFC_Design_LoadConnection_Init.m'')); ', ...
    'clear modelFile']);

loadPath=[modelName '/Load_Profile'];
chart=find(sfroot,'-isa','Stateflow.EMChart','Path',loadPath);
assert(~isempty(chart),'Load_Profile MATLAB Function block was not found.');
chart.Script=loadProfileCode();
addParameters(loadPath,{ ...
    'load_connection_strategy','load_stage_interval_s', ...
    'load_conductance_ramp_time_s'});
setAllDoubleScalar(loadPath);

save_system(modelName,modelFile);
close_system(modelName,0);
fprintf('Created load-connection work model: %s\n',modelFile);

function code=loadProfileCode()
code=sprintf([ ...
'function Rload = fcn(t,startupEnable,load_step_mode,Rload_nominal,load_step_time,Rload_precharge,load_connection_strategy,load_stage_interval_s,load_conductance_ramp_time_s)\n', ...
'%% The sequencer supplies one common load-permission edge for every strategy.\n', ...
'persistent enableTime previousEnable\n', ...
'if isempty(enableTime), enableTime=0; previousEnable=0; end\n', ...
'if startupEnable>=0.5 && previousEnable<0.5, enableTime=t; end\n', ...
'previousEnable=startupEnable;\n', ...
'if startupEnable<0.5\n', ...
' Rload=Rload_precharge; return;\n', ...
'end\n', ...
'elapsed=max(t-enableTime,0);\n', ...
'if load_connection_strategy==1\n', ...
' %% Three discrete conductance levels: 160, 80 and 40 ohm.\n', ...
' if elapsed<load_stage_interval_s\n', ...
'  Rload=4*Rload_nominal;\n', ...
' elseif elapsed<2*load_stage_interval_s\n', ...
'  Rload=2*Rload_nominal;\n', ...
' else\n', ...
'  Rload=Rload_nominal;\n', ...
' end\n', ...
'elseif load_connection_strategy==2\n', ...
' %% Linear load-conductance ramp from effectively open circuit to 1/Rnom.\n', ...
' alpha=min(max(elapsed/load_conductance_ramp_time_s,0),1);\n', ...
' conductance=(1-alpha)/Rload_precharge+alpha/Rload_nominal;\n', ...
' Rload=1/max(conductance,1/Rload_precharge);\n', ...
'elseif load_connection_strategy==0\n', ...
' Rload=Rload_nominal;\n', ...
'elseif load_step_mode==1\n', ...
' %% Retain the old diagnostic modes for traceability; not used in this study.\n', ...
' if t<load_step_time, Rload=2*Rload_nominal; else, Rload=Rload_nominal; end\n', ...
'elseif load_step_mode==2\n', ...
' if t<load_step_time, Rload=Rload_nominal; else, Rload=2*Rload_nominal; end\n', ...
'else\n', ...
' Rload=Rload_nominal;\n', ...
'end\n']);
end

function addParameters(blockPath,names)
chart=find(sfroot,'-isa','Stateflow.EMChart','Path',blockPath);
for index=1:numel(names)
    items=find(chart,'-isa','Stateflow.Data','Name',names{index});
    if isempty(items), item=Stateflow.Data(chart); item.Name=names{index}; else, item=items(1); end
    item.Scope='Parameter'; item.Props.Array.Size='1';
end
end

function setAllDoubleScalar(blockPath)
chart=find(sfroot,'-isa','Stateflow.EMChart','Path',blockPath);
items=find(chart,'-isa','Stateflow.Data');
for index=1:numel(items)
    items(index).DataType='double';
    items(index).Props.Array.Size='1';
end
end
