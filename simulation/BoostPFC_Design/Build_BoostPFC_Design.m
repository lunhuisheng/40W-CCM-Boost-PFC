% Build_BoostPFC_Design
% Creates a new model from an empty Simulink canvas.  It does not copy the
% repository example or either existing work model.

clear;
bdclose('all');

designDir = fileparts(mfilename('fullpath'));
modelName = 'BoostPFC_Design';
modelFile = fullfile(designDir, [modelName '.slx']);
initFile = fullfile(designDir, 'BoostPFC_Design_Init.m');
run(initFile);

if isfile(modelFile)
    error('BoostPFC_Design:ModelExists', ...
        'Refusing to overwrite existing design model: %s', modelFile);
end

new_system(modelName);
open_system(modelName);

set_param(modelName, ...
    'SolverType', 'Fixed-step', ...
    'Solver', 'FixedStepDiscrete', ...
    'FixedStep', 'Ts_sim', ...
    'StartTime', '0', ...
    'StopTime', 'sim_stop_time', ...
    'SignalLogging', 'on', ...
    'SignalLoggingName', 'logsout', ...
    'ReturnWorkspaceOutputs', 'on', ...
    'SaveTime', 'off', ...
    'SaveOutput', 'off');

initCallback = [ ...
    'modelFile = get_param(bdroot, ''FileName''); ' ...
    'run(fullfile(fileparts(modelFile), ''BoostPFC_Design_Init.m'')); ' ...
    'clear modelFile'];
set_param(modelName, 'PreLoadFcn', '', 'InitFcn', initCallback);

% Top-level source and rectifier.
add_block('simulink/Sources/Sine Wave', [modelName '/AC_Source_20_to_28_Vrms'], ...
    'Amplitude', 'sqrt(2)*Vac_rms', ...
    'Frequency', '2*pi*f_line', ...
    'Phase', '0', ...
    'SampleTime', 'Ts_sim', ...
    'Position', [35 100 135 140]);

add_block('simulink/Math Operations/Abs', [modelName '/Bridge_Rectifier_abs'], ...
    'Position', [175 100 215 140]);
add_block('simulink/Math Operations/Bias', [modelName '/Bridge_Diode_Drops'], ...
    'Bias', '-2*Vf_bridge_effective', ...
    'Position', [250 100 340 140]);
add_block('simulink/Discontinuities/Saturation', [modelName '/Rectified_Voltage_Clamp'], ...
    'LowerLimit', '0', 'UpperLimit', 'inf', ...
    'Position', [380 100 465 140]);

% Load profile.
add_block('simulink/Sources/Clock', [modelName '/Time'], ...
    'Position', [40 440 70 470]);
add_block('simulink/User-Defined Functions/MATLAB Function', ...
    [modelName '/Load_Profile'], 'Position', [150 425 285 485]);
setMatlabFunction([modelName '/Load_Profile'], loadProfileCode());
addParameterData([modelName '/Load_Profile'], ...
      {'load_step_mode','Rload_nominal','load_step_time', ...
      'load_enable_time','Rload_precharge'});

% Controller and power-stage blocks are independently authored algorithms.
add_block('simulink/User-Defined Functions/MATLAB Function', ...
    [modelName '/Average_Current_Mode_Control'], ...
    'Position', [570 210 795 355]);
setMatlabFunction([modelName '/Average_Current_Mode_Control'], controllerCode());
addParameterData([modelName '/Average_Current_Mode_Control'], ...
    {'Ts_sim','f_sw','Vout_ref','Vac_rms','Kp_v','Ki_v','Kp_i','Ki_i', ...
     'Ipk_limit','duty_min','duty_max','softstart_time','precharge_release_time'});

add_block('simulink/User-Defined Functions/MATLAB Function', ...
    [modelName '/Boost_Power_Stage_Switched'], ...
    'Position', [900 90 1115 245]);
setMatlabFunction([modelName '/Boost_Power_Stage_Switched'], plantCode());
addParameterData([modelName '/Boost_Power_Stage_Switched'], ...
    {'Ts_sim','L_boost','C_out','rL_effective','Rds_on_effective', ...
     'Vf_boost_effective'});

% One-sample measurement delays remove a numerical algebraic loop and model
% the digital sampling delay.
add_block('simulink/Discrete/Unit Delay', [modelName '/iL_ADC_Delay'], ...
    'SampleTime', 'Ts_sim', 'InitialCondition', '0', ...
    'Position', [1180 280 1230 315]);
add_block('simulink/Discrete/Unit Delay', [modelName '/Vo_ADC_Delay'], ...
    'SampleTime', 'Ts_sim', 'InitialCondition', '0', ...
    'Position', [1180 340 1230 375]);

% Standard Simulink blocks implement the temporary input precharge path.
add_block('simulink/Math Operations/Gain', [modelName '/Precharge_R_Drop'], ...
    'Gain', 'precharge_resistance', 'Position', [500 70 555 100]);
add_block('simulink/Math Operations/Sum', [modelName '/Precharge_Voltage_Subtract'], ...
    'Inputs', '+-', 'Position', [590 95 620 135]);
add_block('simulink/Discontinuities/Saturation', [modelName '/Precharge_Voltage_Clamp'], ...
    'LowerLimit', '0', 'UpperLimit', 'inf', 'Position', [650 95 735 135]);
add_block('simulink/Sources/Step', [modelName '/Precharge_Bypass_Command'], ...
    'Time', 'precharge_release_time', 'Before', '0', 'After', '1', ...
    'SampleTime', 'Ts_sim', 'Position', [650 35 735 65]);
add_block('simulink/Signal Routing/Switch', [modelName '/Precharge_Bypass_Switch'], ...
    'Threshold', '0.5', 'Criteria', 'u2 >= Threshold', ...
    'Position', [780 80 835 145]);

% AC input current sign reconstruction on the source side of the bridge.
add_block('simulink/Math Operations/Sign', [modelName '/AC_Polarity'], ...
    'Position', [175 20 215 55]);
add_block('simulink/Math Operations/Product', [modelName '/AC_Input_Current'], ...
    'Position', [1280 115 1325 160]);

% Scope groups are for interactive inspection; automated scripts use logsout.
add_block('simulink/Signal Routing/Mux', [modelName '/Startup_Mux'], ...
    'Inputs', '4', 'Position', [1390 215 1395 315]);
add_block('simulink/Sinks/Scope', [modelName '/Startup_Scope'], ...
    'Position', [1450 235 1505 290]);
add_block('simulink/Signal Routing/Mux', [modelName '/PFC_Mux'], ...
    'Inputs', '4', 'Position', [1390 355 1395 455]);
add_block('simulink/Sinks/Scope', [modelName '/PFC_Scope'], ...
    'Position', [1450 375 1505 430]);

% Wiring.
connect(modelName, 'AC_Source_20_to_28_Vrms/1', 'Bridge_Rectifier_abs/1', 'vac');
connect(modelName, 'Bridge_Rectifier_abs/1', 'Bridge_Diode_Drops/1', '');
connect(modelName, 'Bridge_Diode_Drops/1', 'Rectified_Voltage_Clamp/1', 'vrect');
connect(modelName, 'AC_Source_20_to_28_Vrms/1', 'AC_Polarity/1', '');
connect(modelName, 'Time/1', 'Load_Profile/1', 'time');

connect(modelName, 'Rectified_Voltage_Clamp/1', 'Precharge_Voltage_Subtract/1', '');
connect(modelName, 'iL_ADC_Delay/1', 'Precharge_R_Drop/1', '');
connect(modelName, 'Precharge_R_Drop/1', 'Precharge_Voltage_Subtract/2', '');
connect(modelName, 'Precharge_Voltage_Subtract/1', 'Precharge_Voltage_Clamp/1', '');
connect(modelName, 'Rectified_Voltage_Clamp/1', 'Precharge_Bypass_Switch/1', '');
connect(modelName, 'Precharge_Bypass_Command/1', 'Precharge_Bypass_Switch/2', '');
connect(modelName, 'Precharge_Voltage_Clamp/1', 'Precharge_Bypass_Switch/3', '');
connect(modelName, 'Precharge_Bypass_Switch/1', 'Boost_Power_Stage_Switched/1', '');
connect(modelName, 'Average_Current_Mode_Control/3', 'Boost_Power_Stage_Switched/2', 'pwm');
connect(modelName, 'Load_Profile/1', 'Boost_Power_Stage_Switched/3', 'Rload');

connect(modelName, 'Time/1', 'Average_Current_Mode_Control/1', '');
connect(modelName, 'Vo_ADC_Delay/1', 'Average_Current_Mode_Control/2', '');
connect(modelName, 'Rectified_Voltage_Clamp/1', 'Average_Current_Mode_Control/3', '');
connect(modelName, 'iL_ADC_Delay/1', 'Average_Current_Mode_Control/4', '');

connect(modelName, 'Boost_Power_Stage_Switched/1', 'iL_ADC_Delay/1', 'iL');
connect(modelName, 'Boost_Power_Stage_Switched/2', 'Vo_ADC_Delay/1', 'vout');
connect(modelName, 'AC_Polarity/1', 'AC_Input_Current/1', '');
connect(modelName, 'Boost_Power_Stage_Switched/1', 'AC_Input_Current/2', 'iac');

% Startup scope: vout, iL, current reference, soft-start reference.
connect(modelName, 'Boost_Power_Stage_Switched/2', 'Startup_Mux/1', '');
connect(modelName, 'Boost_Power_Stage_Switched/1', 'Startup_Mux/2', '');
connect(modelName, 'Average_Current_Mode_Control/1', 'Startup_Mux/3', 'iL_ref');
connect(modelName, 'Average_Current_Mode_Control/5', 'Startup_Mux/4', 'vref_soft');
connect(modelName, 'Startup_Mux/1', 'Startup_Scope/1', '');

% PFC scope: AC voltage/current, rectified voltage and PWM.
connect(modelName, 'AC_Source_20_to_28_Vrms/1', 'PFC_Mux/1', '');
connect(modelName, 'AC_Input_Current/1', 'PFC_Mux/2', '');
connect(modelName, 'Rectified_Voltage_Clamp/1', 'PFC_Mux/3', '');
connect(modelName, 'Average_Current_Mode_Control/3', 'PFC_Mux/4', '');
connect(modelName, 'PFC_Mux/1', 'PFC_Scope/1', '');

% Explicitly log all required measurements.
markLogged(modelName, 'AC_Source_20_to_28_Vrms', 1, 'vac');
markLogged(modelName, 'AC_Input_Current', 1, 'iac');
markLogged(modelName, 'Rectified_Voltage_Clamp', 1, 'vrect');
markLogged(modelName, 'Boost_Power_Stage_Switched', 1, 'iL');
markLogged(modelName, 'Boost_Power_Stage_Switched', 2, 'vout');
markLogged(modelName, 'Boost_Power_Stage_Switched', 3, 'iDiode');
markLogged(modelName, 'Boost_Power_Stage_Switched', 4, 'iMosfet');
markLogged(modelName, 'Average_Current_Mode_Control', 1, 'iL_ref');
markLogged(modelName, 'Average_Current_Mode_Control', 2, 'duty');
markLogged(modelName, 'Average_Current_Mode_Control', 3, 'pwm');
markLogged(modelName, 'Average_Current_Mode_Control', 4, 'voltage_loop_command');
markLogged(modelName, 'Average_Current_Mode_Control', 5, 'vref_soft');
markLogged(modelName, 'Load_Profile', 1, 'Rload');

annotationText = sprintf([ ...
    'SELF-DESIGNED 40 W CCM BOOST PFC - SWITCHED BEHAVIORAL MODEL\n', ...
    'Power flow: 20-28 Vac -> full-wave bridge -> 470 uH boost inductor -> ', ...
    'MOSFET/boost diode switching states -> 2200 uF output -> load\n', ...
    'Non-ideal assumptions: bridge and boost diode drops, MOSFET Rds(on), ', ...
    'inductor ESR. Reverse recovery, magnetic saturation and capacitor ESR ', ...
    'are not yet included.\n', ...
    'Startup protection: parameterized precharge resistor and timed bypass/PWM enable.']);
modelNote = Simulink.Annotation(modelName, annotationText);
modelNote.Position = [470 10 1190 70];

save_system(modelName, modelFile);
close_system(modelName, 0);
fprintf('Created independent model: %s\n', modelFile);

function connect(modelName, sourcePort, destinationPort, signalName)
    lineHandle = add_line(modelName, sourcePort, destinationPort, ...
        'autorouting', 'on');
    if ~isempty(signalName)
        set_param(lineHandle, 'Name', signalName);
    end
end

function markLogged(modelName, blockName, portNumber, loggingName)
    portHandles = get_param([modelName '/' blockName], 'PortHandles');
    outputPort = portHandles.Outport(portNumber);
    set_param(outputPort, 'DataLogging', 'on', ...
        'DataLoggingNameMode', 'Custom', ...
        'DataLoggingName', loggingName);
end

function setMatlabFunction(blockPath, codeText)
    chart = find(sfroot, '-isa', 'Stateflow.EMChart', 'Path', blockPath);
    chart.Script = codeText;
end

function addParameterData(blockPath, names)
    chart = find(sfroot, '-isa', 'Stateflow.EMChart', 'Path', blockPath);
    for index = 1:numel(names)
        dataObject = Stateflow.Data(chart);
        dataObject.Name = names{index};
        dataObject.Scope = 'Parameter';
    end
end

function code = loadProfileCode()
    code = sprintf([ ...
        'function Rload = fcn(t)\n', ...
        '%% Load is open during precharge, then the selected profile is connected.\n', ...
        'if t < load_enable_time\n', ...
        '    Rload = Rload_precharge;\n', ...
        'elseif load_step_mode == 1\n', ...
        '    if t < load_step_time, Rload = 2*Rload_nominal; else, Rload = Rload_nominal; end\n', ...
        'elseif load_step_mode == 2\n', ...
        '    if t < load_step_time, Rload = Rload_nominal; else, Rload = 2*Rload_nominal; end\n', ...
        'else\n', ...
        '    Rload = Rload_nominal;\n', ...
        'end\n']);
end

function code = controllerCode()
    code = sprintf([ ...
        'function [iRef,duty,pwm,vLoop,vRefSoft] = fcn(t,vout,vrect,iL)\n', ...
        '%% Average-current-mode PFC control with PI anti-windup and PWM.\n', ...
        'persistent intV intI carrier\n', ...
        'if isempty(intV), intV=0; intI=0; carrier=0; end\n', ...
        'controlTime = max(t-precharge_release_time,0);\n', ...
        'vRefSoft = Vout_ref*min(controlTime/softstart_time,1);\n', ...
        'eV = vRefSoft-vout;\n', ...
        'vUnsat = Kp_v*eV+intV;\n', ...
        'vLoop = min(max(vUnsat,0),Ipk_limit);\n', ...
        'if (vUnsat==vLoop) || (vUnsat>Ipk_limit && eV<0) || (vUnsat<0 && eV>0)\n', ...
        '    intV = intV+Ki_v*Ts_sim*eV;\n', ...
        'end\n', ...
        'vPeak = max(sqrt(2)*Vac_rms,1);\n', ...
        'iRef = min(Ipk_limit,max(0,vLoop*vrect/vPeak));\n', ...
        'eI = iRef-iL;\n', ...
        'dFeedforward = 1-vrect/max(Vout_ref,1);\n', ...
        'dUnsat = dFeedforward+Kp_i*eI+intI;\n', ...
        'duty = min(max(dUnsat,duty_min),duty_max);\n', ...
        'if (dUnsat==duty) || (dUnsat>duty_max && eI<0) || (dUnsat<duty_min && eI>0)\n', ...
        '    intI = intI+Ki_i*Ts_sim*eI;\n', ...
        'end\n', ...
        'carrier = carrier+f_sw*Ts_sim;\n', ...
        'if carrier>=1, carrier=carrier-floor(carrier); end\n', ...
        'if t<precharge_release_time\n', ...
        '    duty=0; pwm=0;\n', ...
        'else\n', ...
        '    pwm = double(duty>carrier);\n', ...
        'end\n']);
end

function code = plantCode()
    code = sprintf([ ...
        'function [iL,vout,iDiode,iMosfet] = fcn(vin,pwm,Rload)\n', ...
        '%% Cycle-resolved switched boost equations.\n', ...
        'persistent iState vState\n', ...
        'if isempty(iState), iState=0; vState=0; end\n', ...
        'loadCurrent = vState/max(Rload,1e-6);\n', ...
        'if pwm>=0.5\n', ...
        '    di = (vin-iState*(rL_effective+Rds_on_effective))/L_boost;\n', ...
        '    dv = -loadCurrent/C_out;\n', ...
        '    iMosfet = iState; iDiode = 0;\n', ...
        'else\n', ...
        '    if (iState>0) || (vin>vState+Vf_boost_effective)\n', ...
        '        di = (vin-vState-Vf_boost_effective-iState*rL_effective)/L_boost;\n', ...
        '        iDiode = max(iState,0);\n', ...
        '        dv = (iDiode-loadCurrent)/C_out;\n', ...
        '    else\n', ...
        '        di = 0; iState=0; iDiode=0; dv=-loadCurrent/C_out;\n', ...
        '    end\n', ...
        '    iMosfet = 0;\n', ...
        'end\n', ...
        'iState = max(iState+Ts_sim*di,0);\n', ...
        'vState = max(vState+Ts_sim*dv,0);\n', ...
        'iL = iState; vout = vState;\n']);
end
