% Create the controlled-startup model from the verified safe-bypass model.

clear;
bdclose('all');
designDir=fileparts(mfilename('fullpath'));
sourceFile=fullfile(designDir,'BoostPFC_Design_SafeBypass.slx');
modelName='BoostPFC_Design_ControlledStartup';
modelFile=fullfile(designDir,[modelName '.slx']);
if ~isfile(modelFile), copyfile(sourceFile,modelFile); end
run(fullfile(designDir,'BoostPFC_Design_ControlledStartup_Init.m'));
load_system(modelFile);
set_param(modelName,'InitFcn',[ ...
    'modelFile=get_param(bdroot,''FileName''); ', ...
    'run(fullfile(fileparts(modelFile),''BoostPFC_Design_ControlledStartup_Init.m'')); ', ...
    'clear modelFile']);

sequencerPath=[modelName '/Startup_Sequencer'];
setChartScript(sequencerPath,sequencerCode());
setDataScope(sequencerPath,'controllerFault','Input');
setDataScope(sequencerPath,'pwmEnable','Output');
setDataScope(sequencerPath,'loadEnable','Output');
addParameters(sequencerPath,{ ...
    'Ts_sim','safe_output_threshold_V','safe_rectified_threshold_V', ...
    'safe_voltage_difference_max_V','safe_bypass_current_max_A', ...
    'safe_condition_hold_time_s','safe_bypass_timeout_s', ...
    'bypass_settle_min_time_s','pwm_start_current_max_A', ...
    'pwm_start_condition_hold_s','pwm_start_timeout_s', ...
    'startup_ramp_time_s','Vout_ref','load_connect_voltage_tolerance_V', ...
    'load_connect_stable_time_s','load_connect_timeout_s'});
setAllDoubleScalar(sequencerPath);

controllerPath=[modelName '/Average_Current_Mode_Control'];
setChartScript(controllerPath,controllerCode());
setDataScope(controllerPath,'currentLimitActive','Output');
setDataScope(controllerPath,'dutySaturated','Output');
setDataScope(controllerPath,'overcurrentFault','Output');
setDataScope(controllerPath,'currentAmpLimit','Output');
addParameters(controllerPath,{ ...
    'Ts_sim','f_sw','Vout_ref','Vac_rms','Kp_v','Ki_v','Kp_i','Ki_i', ...
    'Ipk_limit','duty_min','duty_max', ...
    'startup_ramp_time_s','startup_current_limit_initial_A', ...
    'actual_peak_cycle_limit_A','actual_peak_fault_limit_A'});
setAllDoubleScalar(controllerPath);

% Save/reload so expanded chart interfaces are visible for wiring.
save_system(modelName,modelFile);
close_system(modelName,0);
load_system(modelFile);

% Remove the safe-bypass test constants and connect sequencer outputs.
removeBranch(modelName,'Safe_Test_Enable_Zero/1','Load_Profile/2');
removeBranch(modelName,'Safe_Test_Enable_Zero/1','Average_Current_Mode_Control/5');
zeroPath=[modelName '/Safe_Test_Enable_Zero'];
if getSimulinkBlockHandle(zeroPath)>=0, delete_block(zeroPath); end
connectIfMissing(modelName,'Startup_Sequencer/3','Average_Current_Mode_Control/5');
connectIfMissing(modelName,'Startup_Sequencer/4','Load_Profile/2');

% Feed the controller's latched overcurrent fault back through one sample of
% delay, avoiding an algebraic loop while forcing the sequencer safe state.
faultDelayPath=[modelName '/Overcurrent_Fault_Delay'];
if getSimulinkBlockHandle(faultDelayPath)<0
    add_block('simulink/Discrete/Unit Delay',faultDelayPath, ...
        'InitialCondition','0','SampleTime','Ts_sim', ...
        'Position',[860 340 910 370]);
end
connectIfMissing(modelName,'Average_Current_Mode_Control/8','Overcurrent_Fault_Delay/1');
connectIfMissing(modelName,'Overcurrent_Fault_Delay/1','Startup_Sequencer/5');

% Terminate new diagnostic outputs while preserving signal logging.
diagnostics={ ...
    6,'Current_Limit_Terminator','current_limit_active'; ...
    7,'Duty_Saturation_Terminator','duty_saturated'; ...
    9,'Current_Amp_Limit_Terminator','current_amp_limit'};
for index=1:size(diagnostics,1)
    blockName=diagnostics{index,2};
    path=[modelName '/' blockName];
    if getSimulinkBlockHandle(path)<0
        add_block('simulink/Sinks/Terminator',path, ...
            'Position',[980 390+35*index 1000 410+35*index]);
    end
    connectIfMissing(modelName,sprintf('Average_Current_Mode_Control/%d',diagnostics{index,1}), ...
        [blockName '/1']);
    markLoggedSignal(controllerPath,diagnostics{index,1},diagnostics{index,3});
end
markLoggedSignal(controllerPath,8,'overcurrent_fault');
markLoggedSignal(sequencerPath,1,'controlled_bypass_enable');
markLoggedSignal(sequencerPath,2,'controlled_startup_state');
markLoggedSignal(sequencerPath,3,'controlled_pwm_enable');
markLoggedSignal(sequencerPath,4,'controlled_load_enable');

save_system(modelName,modelFile);
close_system(modelName,0);
fprintf('Created controlled-startup model: %s\n',modelFile);

function code=sequencerCode()
code=sprintf([ ...
'function [startupEnable,startupState,pwmEnable,loadEnable] = fcn(t,vout,vrect,iL,controllerFault)\n', ...
'%% States: 0 precharge, 1 bypass wait, 2 PWM ramp, 3 wait load, 4 run.\n', ...
'%% Faults: -1 precharge timeout, -2 overcurrent, -3 startup timeout.\n', ...
'persistent state validDuration stateEntryTime stableDuration\n', ...
'if isempty(state), state=0; validDuration=0; stateEntryTime=0; stableDuration=0; end\n', ...
'if controllerFault>=0.5, state=-2; end\n', ...
'if state==0\n', ...
' voltageDifference=abs(vrect-vout);\n', ...
' conditions=(vout>=safe_output_threshold_V) && ...\n', ...
'  (vrect>=safe_rectified_threshold_V) && ...\n', ...
'  (voltageDifference<=safe_voltage_difference_max_V) && ...\n', ...
'  (iL<=safe_bypass_current_max_A);\n', ...
' if conditions, validDuration=validDuration+Ts_sim; else, validDuration=0; end\n', ...
' if validDuration>=safe_condition_hold_time_s\n', ...
'  state=1; stateEntryTime=t; validDuration=0;\n', ...
' elseif t>=safe_bypass_timeout_s\n', ...
'  state=-1;\n', ...
' end\n', ...
'elseif state==1\n', ...
' conditions=(t-stateEntryTime>=bypass_settle_min_time_s) && (iL<=pwm_start_current_max_A);\n', ...
' if conditions, validDuration=validDuration+Ts_sim; else, validDuration=0; end\n', ...
' if validDuration>=pwm_start_condition_hold_s\n', ...
'  state=2; stateEntryTime=t; validDuration=0;\n', ...
' elseif t>=pwm_start_timeout_s\n', ...
'  state=-3;\n', ...
' end\n', ...
'elseif state==2\n', ...
' if t-stateEntryTime>=startup_ramp_time_s, state=3; stateEntryTime=t; stableDuration=0; end\n', ...
'elseif state==3\n', ...
' if abs(vout-Vout_ref)<=load_connect_voltage_tolerance_V\n', ...
'  stableDuration=stableDuration+Ts_sim;\n', ...
' else\n', ...
'  stableDuration=0;\n', ...
' end\n', ...
' if stableDuration>=load_connect_stable_time_s\n', ...
'  state=4; stateEntryTime=t;\n', ...
' elseif t>=load_connect_timeout_s\n', ...
'  state=-3;\n', ...
' end\n', ...
'end\n', ...
'startupEnable=double(state>=1 && state<=4);\n', ...
'pwmEnable=double(state>=2 && state<=4);\n', ...
'loadEnable=double(state==4);\n', ...
'startupState=double(state);\n']);
end

function code=controllerCode()
code=sprintf([ ...
'function [iRef,duty,pwm,vLoop,vRefSoft,currentLimitActive,dutySaturated,overcurrentFault,currentAmpLimit] = fcn(t,vout,vrect,iL,startupEnable)\n', ...
'%% Average-current control with reference ramp and measured peak limiter.\n', ...
'persistent intV intI carrier enableTime startVoltage faultLatched\n', ...
'if isempty(intV), intV=0; intI=0; carrier=0; enableTime=-1; startVoltage=0; faultLatched=false; end\n', ...
'if startupEnable>=0.5 && iL>=actual_peak_fault_limit_A, faultLatched=true; end\n', ...
'overcurrentFault=double(faultLatched);\n', ...
'currentLimitActive=0; dutySaturated=0; currentAmpLimit=startup_current_limit_initial_A;\n', ...
'if startupEnable<0.5 || faultLatched\n', ...
' intV=0; intI=0; carrier=0; enableTime=-1;\n', ...
' iRef=0; duty=0; pwm=0; vLoop=0; vRefSoft=vout; return;\n', ...
'end\n', ...
'if enableTime<0, enableTime=t; startVoltage=vout; end\n', ...
'alpha=min(max((t-enableTime)/startup_ramp_time_s,0),1);\n', ...
'vRefSoft=startVoltage+(Vout_ref-startVoltage)*alpha;\n', ...
'currentAmpLimit=startup_current_limit_initial_A+alpha*(Ipk_limit-startup_current_limit_initial_A);\n', ...
'eV=vRefSoft-vout; vUnsat=Kp_v*eV+intV;\n', ...
'vLoop=min(max(vUnsat,0),currentAmpLimit);\n', ...
'if (vUnsat==vLoop)||(vUnsat>currentAmpLimit&&eV<0)||(vUnsat<0&&eV>0), intV=intV+Ki_v*Ts_sim*eV; end\n', ...
'vPeak=max(sqrt(2)*Vac_rms,1); iRef=min(currentAmpLimit,max(0,vLoop*vrect/vPeak));\n', ...
'eI=iRef-iL; dFeedforward=1-vrect/max(Vout_ref,1); dUnsat=dFeedforward+Kp_i*eI+intI;\n', ...
'duty=min(max(dUnsat,duty_min),duty_max);\n', ...
'dutySaturated=double(dUnsat<=duty_min || dUnsat>=duty_max);\n', ...
'if (dUnsat==duty)||(dUnsat>duty_max&&eI<0)||(dUnsat<duty_min&&eI>0), intI=intI+Ki_i*Ts_sim*eI; end\n', ...
'carrier=carrier+f_sw*Ts_sim; if carrier>=1, carrier=carrier-floor(carrier); end\n', ...
'if iL>=actual_peak_cycle_limit_A\n', ...
' currentLimitActive=1; pwm=0;\n', ...
'else\n', ...
' pwm=double(duty>carrier);\n', ...
'end\n']);
end

function setChartScript(blockPath,codeText)
chart=find(sfroot,'-isa','Stateflow.EMChart','Path',blockPath); chart.Script=codeText;
end

function setDataScope(blockPath,name,scope)
chart=find(sfroot,'-isa','Stateflow.EMChart','Path',blockPath);
items=find(chart,'-isa','Stateflow.Data','Name',name);
if isempty(items), item=Stateflow.Data(chart); item.Name=name; else, item=items(1); end
item.Scope=scope; item.Props.Array.Size='1';
end

function addParameters(blockPath,names)
chart=find(sfroot,'-isa','Stateflow.EMChart','Path',blockPath);
for index=1:numel(names)
 items=find(chart,'-isa','Stateflow.Data','Name',names{index});
 if isempty(items), item=Stateflow.Data(chart); item.Name=names{index}; else, item=items(1); end
 item.Scope='Parameter'; item.Props.Array.Size='1';
end
end

function setAllDoubleScalar(blockPath)
chart=find(sfroot,'-isa','Stateflow.EMChart','Path',blockPath);
items=find(chart,'-isa','Stateflow.Data');
for index=1:numel(items)
 items(index).DataType='double';
 items(index).Props.Array.Size='1';
end
end

function removeBranch(modelName,sourcePort,destinationPort)
try, delete_line(modelName,sourcePort,destinationPort); catch, end
end

function connectIfMissing(modelName,sourcePort,destinationPort)
block=extractBefore(destinationPort,'/'); number=str2double(extractAfter(destinationPort,'/'));
ports=get_param([modelName '/' block],'PortHandles');
if get_param(ports.Inport(number),'Line')==-1
 add_line(modelName,sourcePort,destinationPort,'autorouting','on');
end
end

function markLoggedSignal(blockPath,portNumber,signalName)
ports=get_param(blockPath,'PortHandles'); lineHandle=get_param(ports.Outport(portNumber),'Line');
set_param(lineHandle,'Name',signalName);
set_param(ports.Outport(portNumber),'DataLogging','on','DataLoggingNameMode','SignalName');
end
